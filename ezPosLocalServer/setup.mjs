#!/usr/bin/env node
/**
 * ezPos Local Server setup (Phase 2 — LAN mode).
 *
 * GUIDED SETUP for the shop's Windows machine. UNVERIFIED ON REAL WINDOWS
 * HARDWARE (developed/tested on Linux) — treat the checklist in
 * DEPLOYMENT.md as the source of truth and expect to run steps manually on
 * first deployment.
 *
 * What it does:
 *   1. Verifies Node 22 and a reachable PostgreSQL 16 (psql/pg_ctl on PATH
 *      or explicit flags).
 *   2. Creates the local database and role (idempotent).
 *   3. Generates the four production-critical secrets (AUTH_JWT_SECRET,
 *      INTEGRATION_ENCRYPTION_KEY, BACKUP_ENCRYPTION_KEY + a random
 *      BACKUP_ENCRYPTION_KEY_VERSION) into ezPosBackend/.env.
 *   4. Runs the migrations via scripts/apply-migration.mjs.
 *   5. Writes the sync-agent configuration (cloud URL + terminal credential)
 *      once the operator pairs this server on the cloud (prints the code).
 *   6. Optionally registers a Windows service via NSSM or Task Scheduler
 *      (both paths documented; --service nssm|task|none).
 *
 * Usage:
 *   node setup.mjs [--db ezpos_local] [--db-user ezpos_local]
 *                  [--pg-url postgresql://user:pass@localhost:5432/postgres]
 *                  [--cloud https://api.ezpos.com] [--service nssm|task|none]
 *
 * This script never prints secrets after writing them.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import process from "node:process";

const args = process.argv.slice(2);
function argValue(name, fallback) {
  const index = args.indexOf(name);
  return index >= 0 && args[index + 1] ? args[index + 1] : fallback;
}

const repoRoot = path.resolve(new URL("..", import.meta.url).pathname);
const backendDir = path.join(repoRoot, "ezPosBackend");
const dataDir = process.env.EZPOS_LOCAL_DATA_DIR || path.join(homedir(), ".ezpos-local");

const DB_NAME = argValue("--db", "ezpos_local");
const DB_USER = argValue("--db-user", "ezpos_local");
const PG_ADMIN_URL = argValue("--pg-url", "");
const CLOUD_URL = argValue("--cloud", "");
const SERVICE_MODE = argValue("--service", "none");

function log(step, message) {
  console.log(`[setup:${step}] ${message}`);
}
function fail(step, message) {
  console.error(`[setup:${step}] FAILED: ${message}`);
  process.exit(1);
}
function run(cmd, args_, options = {}) {
  const result = spawnSync(cmd, args_, { stdio: "inherit", shell: false, ...options });
  if (result.status !== 0) {
    fail(cmd, `${cmd} ${args_.join(" ")} exited ${result.status}`);
  }
}

// 1. Node version guard — the backend targets Node 22 (.nvmrc).
const nodeMajor = Number(process.versions.node.split(".")[0]);
if (nodeMajor < 22) {
  fail("node", `Node 22+ required (found ${process.versions.node}). Install from https://nodejs.org.`);
}
log("node", `Node ${process.versions.node} OK`);

// 2. Local database (skip when the operator supplies a ready DATABASE_URL).
const DB_PASSWORD = randomBytes(18).toString("base64url");
const DATABASE_URL =
  argValue("--database-url", "") ||
  `postgresql://${encodeURIComponent(DB_USER)}:${encodeURIComponent(DB_PASSWORD)}@localhost:5432/${DB_NAME}`;

if (PG_ADMIN_URL) {
  log("db", `Creating role/database ${DB_USER}/${DB_NAME} (idempotent)...`);
  run("psql", [PG_ADMIN_URL, "-v", "ON_ERROR_STOP=1", "-c", `DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${DB_USER}') THEN CREATE ROLE ${DB_USER} LOGIN PASSWORD '${DB_PASSWORD}'; ELSE ALTER ROLE ${DB_USER} PASSWORD '${DB_PASSWORD}'; END IF; END $$;`]);
  run("psql", [PG_ADMIN_URL, "-tAc", `SELECT 1 FROM pg_database WHERE datname = '${DB_NAME}'`]);
  // createdb if missing (ignore the already-exists error):
  const check = spawnSync("psql", [PG_ADMIN_URL, "-tAc", `SELECT 1 FROM pg_database WHERE datname = '${DB_NAME}'`], { encoding: "utf8" });
  if (check.stdout.trim() !== "1") {
    run("createdb", ["-h", "localhost", "-U", DB_USER, DB_NAME]);
  }
} else {
  log("db", "No --pg-url given: expecting DATABASE_URL to point at an EXISTING local database (see DEPLOYMENT.md step 2).");
}

// 3. Secrets + .env
mkdirSync(dataDir, { recursive: true });
const envPath = path.join(backendDir, ".env");
const envLines = [
  `# ezPos LOCAL SERVER (LAN mode) — generated by ezPosLocalServer/setup.mjs`,
  `# Keep this file private. Losing BACKUP_ENCRYPTION_KEY makes backups unreadable.`,
  `AUTH_JWT_SECRET=${randomBytes(48).toString("base64url")}`,
  `INTEGRATION_ENCRYPTION_KEY=${randomBytes(32).toString("base64url")}`,
  `BACKUP_ENCRYPTION_KEY=${randomBytes(32).toString("base64url")}`,
  `BACKUP_ENCRYPTION_KEY_VERSION=1`,
  `DATABASE_URL=${DATABASE_URL}`,
  `PORT=3000`,
  `# LAN sync agent (Phase 2):`,
  `EZPOS_SYNC_ENABLED=true`,
  `EZPOS_SYNC_CLOUD_URL=${CLOUD_URL || "https://api.ezpos.com"}`,
  `EZPOS_SYNC_INTERVAL_SECONDS=60`,
  `EZPOS_SYNC_TERMINAL_ID=`,
  `EZPOS_SYNC_TERMINAL_SECRET=`,
  ``,
];
writeFileSync(envPath, envLines.join("\n"), { mode: 0o600 });
log("env", `Wrote ${envPath} (0600). Secrets are NOT printed.`);

// 4. Dependencies + migrations
log("install", "npm ci (backend)...");
run("npm", ["ci", "--prefix", backendDir]);
log("migrate", "Applying ALL migrations in order to the local database...");
const { readdirSync } = await import("node:fs");
const migrationFiles = readdirSync(path.join(backendDir, "drizzle"))
  .filter((f) => /^\d{4}_.*\.sql$/.test(f))
  .sort();
for (const file of migrationFiles) {
  run("node", [path.join(backendDir, "scripts", "apply-migration.mjs"), path.join("drizzle", file)], {
    cwd: backendDir,
  });
}

// 5. Sync-agent pairing checklist (interactive step — cannot be automated
// without cloud credentials, so we print exactly what to do).
console.log(`
=============================================================
 NEXT STEP — pair this server as the shop's SYNC AGENT
=============================================================
1. In the CLOUD POS: Settings -> Hardware -> Pair a terminal
   (name it e.g. "LAN Server").
2. Mark that terminal as the sync agent:
   PATCH /api/terminals/<id> { "isSyncAgent": true }
   (Settings -> Hardware -> "Make sync agent" action.)
3. Copy the terminal SECRET (shown once at pairing) and run:
     node ${path.join("ezPosLocalServer", "pair.mjs")} --terminal-id <ID> --secret <SECRET>
   (writes EZPOS_SYNC_TERMINAL_ID / _SECRET into ${envPath})
4. Start the server:  npm start  (or the registered service)
=============================================================
`);

// 6. Service registration (optional; both UNVERIFIED on real Windows).
if (SERVICE_MODE === "nssm") {
  log("service", "NSSM registration (run from an ADMIN shell):");
  console.log(`  nssm install ezPosLocal "C:\\Program Files\\nodejs\\node.exe" dist/server.js`);
  console.log(`  nssm set ezPosLocal AppDirectory ${backendDir}`);
  console.log(`  nssm set ezPosLocal AppStdout ${path.join(dataDir, "service.log")}`);
  console.log(`  nssm set ezPosLocal AppStderr ${path.join(dataDir, "service.err.log")}`);
  console.log(`  nssm start ezPosLocal`);
} else if (SERVICE_MODE === "task") {
  log("service", "Task Scheduler registration (run from an ADMIN shell):");
  console.log(`  schtasks /Create /SC ONSTART /TN ezPosLocal /TR "cmd /c cd /d ${backendDir} && npm start" /RU SYSTEM`);
} else {
  log("service", "Skipped (--service none). Start manually with: npm start");
}

log("done", "Setup complete. See ezPosLocalServer/DEPLOYMENT.md for the go-live checklist.");
